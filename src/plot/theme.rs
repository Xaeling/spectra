//! 图主题：字体、线宽、字号与留白。所有尺寸单位是 pt（渲染时乘 px_per_pt）。

use crate::core::color::Rgba;
use crate::core::graph::PlotThemeId;
use crate::plot::text::Family;

#[derive(Clone, Copy, Debug)]
pub struct Theme {
    pub family: Family,
    pub ink: Rgba,
    pub axis: Rgba,
    pub grid: Rgba,
    pub muted: Rgba,
    pub frame: Rgba,
    pub font_title: f32,
    pub font_axis_title: f32,
    pub font_tick: f32,
    pub font_legend: f32,
    pub font_annotation: f32,
    pub axis_width: f32,
    pub tick_len: f32,
    pub closed_frame: bool,
    pub grid_dash: bool,
    pub bar_alpha: u8,
    pub point_edge: bool,
}

