/// 柱体内部填充的不透明度（与原实现一致：85%）。
pub const FILL_ALPHA: f32 = 0.85;

// ── HSL 转换 ────────────────────────────────────────────────────────────────
pub fn rgb_to_hsl(c: Rgba) -> (f32, f32, f32) {
    let r = c[0] as f32 / 255.0;
    let g = c[1] as f32 / 255.0;
    let b = c[2] as f32 / 255.0;
    let max = r.max(g).max(b);
    let min = r.min(g).min(b);
    let l = (max + min) / 2.0;
    let d = max - min;
    if d == 0.0 {
        return (0.0, 0.0, l);
    }
    let s = if l > 0.5 {
        d / (2.0 - max - min)
    } else {
        d / (max + min)
    };
    let h = if (max - r).abs() < 1e-6 {
        ((g - b) / d) % 6.0
    } else if (max - g).abs() < 1e-6 {
        (b - r) / d + 2.0
    } else {
        (r - g) / d + 4.0
    };
    let h = h * 60.0;
    (if h < 0.0 { h + 360.0 } else { h }, s, l)
}

fn hue2rgb(p: f32, q: f32, t: f32) -> f32 {
    let mut t = t;
    if t < 0.0 {
        t += 1.0;
    }
    if t > 1.0 {
        t -= 1.0;
    }
    if t < 1.0 / 6.0 {
        p + (q - p) * 6.0 * t
    } else if t < 1.0 / 2.0 {
        q
    } else if t < 2.0 / 3.0 {
        p + (q - p) * (2.0 / 3.0 - t) * 6.0
    } else {
        p
    }
}

pub fn hsl_to_rgb(h: f32, s: f32, l: f32, a: u8) -> Rgba {
    if s == 0.0 {
        let v = (l * 255.0).round().clamp(0.0, 255.0) as u8;
        return [v, v, v, a];
    }
    let q = if l < 0.5 { l * (1.0 + s) } else { l + s - l * s };
    let p = 2.0 * l - q;
    let hk = h / 360.0;
    let r = hue2rgb(p, q, hk + 1.0 / 3.0);
    let g = hue2rgb(p, q, hk);
    let b = hue2rgb(p, q, hk - 1.0 / 3.0);
    [
        (r * 255.0).round().clamp(0.0, 255.0) as u8,
        (g * 255.0).round().clamp(0.0, 255.0) as u8,
        (b * 255.0).round().clamp(0.0, 255.0) as u8,
        a,
    ]
}

/// 柱体边框色：明度 ×0.40、饱和度 ×3.0（浅填充 ×1.5）；
/// 近中性色 / 近白走灰阶分支 ×0.647。在 HSL 里做，保色相，所以边框不会发黑。
pub fn shade(r: Rgba) -> Rgba {
    let (h, s, l) = rgb_to_hsl(r);
    if s < 0.10 || l > 0.88 {
        // 近中性色 / 近白 → 灰阶分支
        let nl = (l * 0.647).clamp(0.0, 1.0);
        let v = (nl * 255.0).round() as u8;
        return [v, v, v, r[3]];
    }
    let nl = (l * 0.40).clamp(0.0, 1.0); // 明度压到 40%
    let ns = if l > 0.70 {
        (s * 1.5).min(1.0)
    } else {
        (s * 3.0).min(1.0)
    }; // 饱和×3（浅填充×1.5）
    hsl_to_rgb(h, ns, nl, r[3])
}

/// 改 alpha（柱体内部用 85%）。
pub fn with_alpha(r: Rgba, a: f32) -> Rgba {
    [r[0], r[1], r[2], (a.clamp(0.0, 1.0) * 255.0).round() as u8]
}

/// 预混白底：白底画布上，85% 不透明的等价实色。
/// 导出透明背景时用 `with_alpha`；白底导出两者视觉一致，这个更快更稳。
pub fn mix_white(r: Rgba, a: f32) -> Rgba {
    let a = a.clamp(0.0, 1.0);
    let m = |v: u8| (v as f32 * a + 255.0 * (1.0 - a)).round() as u8;
    [m(r[0]), m(r[1]), m(r[2]), 255]
}

// ── 取色 ────────────────────────────────────────────────────────────────────
/// 第 `i` 个数据集的基础色（色板循环取用，色数不固定）。
pub fn color_of(map: usize, i: usize) -> Rgba {
    let cm = &COLORMAPS[map.min(COLORMAPS.len() - 1)];
    cm.colors[i % cm.colors.len()]
}

/// 柱体内部色：基础色 + 85% 不透明（混白底后更浅）。
pub fn fill_of(map: usize, i: usize) -> Rgba {
    with_alpha(color_of(map, i), FILL_ALPHA)
}

/// 柱体内部色（预混白底后的实色版）。
/// 白底画布上与 85% alpha 视觉等价，但不依赖绘图后端的 alpha 混合行为，
/// 结果更确定。透明背景导出时改用 `fill_of`。
pub fn fill_solid(map: usize, i: usize) -> Rgba {
    // 注意：混白只能做一次。之前写成 mix_white(fill_of(..)) 是「先降 alpha 再混白」，
    // 等于把 0.85 用了两遍，散点内芯被洗成近白色 —— 看上去像空心圈而不是实心点。
    mix_white(color_of(map, i), FILL_ALPHA)
}

/// 柱体边框色 / 误差棒色 / 散点描边色：`shade()` 后 100% 不透明。
pub fn edge_of(map: usize, i: usize) -> Rgba {
    shade(color_of(map, i))
}

/// Rgba → `#RRGGBB`，供 UI 侧的色块 / 取色用。
pub fn to_hex(c: Rgba) -> String {
    format!("#{:02X}{:02X}{:02X}", c[0], c[1], c[2])
}

