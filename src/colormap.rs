/// 取配色在当前语言下的显示名。`zh = true` 返回中文名。
pub fn colormap_name(i: usize, zh: bool) -> &'static str {
    if zh {
        COLORMAP_NAMES_ZH
            .get(i)
            .copied()
            .unwrap_or(COLORMAPS[i % COLORMAPS.len()].name)
    } else {
        COLORMAPS[i % COLORMAPS.len()].name
    }
}

/// 全部配色在当前语言下的名字（下拉框用）。
pub fn colormap_names(zh: bool) -> Vec<String> {
    (0..COLORMAPS.len()).map(|i| colormap_name(i, zh).to_string()).collect()
}

