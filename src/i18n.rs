//! 中英双语词条表。
//!
//! 设计：词条用 `K` 枚举做 key（不是字符串），所以拼错的 key 在编译期就会报错，
//! 不会出现「某个界面漏翻译就显示英文」的静默降级。
//!
//! 新增界面文案时：先在 `K` 里加一个变体，再到 `zh()` / `en()` 两个 match 里补齐；
//! 两侧都不填会走 `_ => unreachable!()`，编译期不会拦，所以加完请搜一下自己的 key。

#[derive(Clone, Copy, PartialEq, Eq, Default)]
pub enum Lang {
    #[default]
    Zh,
    En,
}

impl Lang {
    #[allow(dead_code)]
    pub fn label(self) -> &'static str {
        match self {
            Lang::Zh => "中文",
            Lang::En => "English",
        }
    }
}

