/// 按语言翻译一个术语；未命中原样返回。
pub fn stat_term(lang: Lang, s: &str) -> String {
    match lang {
        Lang::Zh => STAT_TERMS
            .iter()
            .find(|(en, _)| *en == s)
            .map(|(_, zh)| (*zh).to_string())
            .unwrap_or_else(|| s.to_string()),
        Lang::En => s.to_string(),
    }
}

/// 整表翻译：对结果表的每一个单元格做术语替换（只替换完全匹配项）。
pub fn translate_rows(lang: Lang, rows: &[Vec<String>]) -> Vec<Vec<String>> {
    match lang {
        Lang::En => rows.to_vec(),
        Lang::Zh => rows
            .iter()
            .map(|r| r.iter().map(|c| stat_term(lang, c)).collect())
            .collect(),
    }
}

/// 结果表标题翻译：形如 "Descriptive statistics of Data 1"，
/// 只翻译 " of " 前面的部分，后面的表名保持原样。
pub fn translate_title(lang: Lang, t: &str) -> String {
    match lang {
        Lang::En => t.to_string(),
        Lang::Zh => match t.split_once(" of ") {
            Some((head, tail)) => format!("{} / {}", stat_term(lang, head), tail),
            None => stat_term(lang, t),
        },
    }
}
